class Codechef {
    public static void main(String[] args) {
        double fuel = 7.0; 
        while ( fuel>1) {
            System.out.println( "Fuel remaining: "+fuel+" liters." ); 
            fuel--;
        }
        System.out.println("Warning! Only 1.0 liter of fuel left. Refuel soon!");  
    }
}
